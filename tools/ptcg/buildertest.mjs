// The Pokémon deck builder without a browser: the paste reader (Pokémon TCG Live and Limitless lists, the old Pokémon
// TCG Online format, lists typed by hand; set codes and numbers, prints the game doesn't have, reprints, typos, cards
// the game doesn't have, more than 4 of a name), the list it writes back (every tournament deck round trips exactly),
// the rules check and what can't be added, the deck's sort, the packed form rooms and replays carry (and a deck only
// found by the exact fingerprint of its cards), and save codes combining two devices' decks.
// Usage: node tools/ptcg/buildertest.mjs
import fs from 'node:fs';
import { cardIndex, parseDeckList, deckToText, printOf } from '../../src/ptcg/decktext.js';
import { deckRules, deckProblems, deckTips, cantAdd, sortDeck, deckLook, handChance, packDeck, unpackDeck, fingerprint, deckRef, registerDeck, registerPacked, findDeck, energyMissing, energyMade } from '../../src/ptcg/customdecks.js';
import { mergeSaves, summarize } from '../../src/ui/savecode.js';

const db = JSON.parse(fs.readFileSync('data/ptcg/cards.json', 'utf8'));
const decks = JSON.parse(fs.readFileSync('data/ptcg/decks.json', 'utf8'));
const ix = cardIndex(db, decks);
let pass = 0, fail = 0;
const ok = (c, msg) => { if (c) pass++; else { fail++; console.log('FAIL', msg); } };
const count = m => [...m.values()].reduce((a, b) => a + b, 0);
const list = m => [...m];

// ---- every tournament deck, written as Pokémon TCG Live does and read back: the same 60 cards
let same = 0;
for (const d of decks) {
  const text = deckToText(sortDeck(d.cards, db), db);
  const r = parseDeckList(text, ix);
  const want = new Map(d.cards);
  if (r.cards.size === want.size && [...want].every(([k, n]) => r.cards.get(k) === n) && !r.missing.length && !r.fixed.length && !r.swapped.length && r.total === 60) same++;
  else console.log('  round trip differs:', d.id, JSON.stringify(list(r.cards)));
  ok(!deckProblems(d.cards, db).length, `${d.id} keeps the rules`);
}
ok(same === decks.length, `every tournament deck round trips (${same}/${decks.length})`);
const drag = decks.find(d => d.id === 'dragapult');
const dragText = deckToText(sortDeck(drag.cards, db), db);
ok(/^Pokémon: 19\n4 Dreepy TWM 128\n4 Drakloak TWM 129\n3 Dragapult ex TWM 130\n/.test(dragText), 'the list starts as Live writes it');
ok(/\n\nTrainer: 32\n/.test(dragText) && /\n\nEnergy: 9\n3 Basic \{R\} Energy SVE 2\n3 Basic \{P\} Energy SVE 5\n3 Basic \{D\} Energy SVE 7\n\nTotal Cards: 60$/.test(dragText), 'Trainer and Energy headings, basic Energy as Live writes it, the total');

// ---- a Pokémon TCG Live / Limitless export
const live = `Pokémon: 12
4 Dreepy TWM 128
4 Drakloak TWM 129
3 Dragapult ex TWM 130
1 Fezandipiti ex SFA 38

Trainer: 33
4 Lillie's Determination MEG 119
4 Battle VIP Pass FST 225
3 Boss's Orders PAL 172
4 Ultra Ball SVI 196
4 Buddy-Buddy Poffin TEF 144
4 Rare Candy SVI 191
1 Unfair Stamp TWM 165
4 Night Stretcher SFA 61
4 Poké Pad POR 81
1 Pokégear 3.0 SVI 186

Energy: 15
5 Basic {P} Energy SVE 5
5 Basic {R} Energy SVE 2
5 Basic {D} Energy SVE 7

Total Cards: 60`;
let r = parseDeckList(live, ix);
ok(r.cards.get('TWM-128') === 4 && r.cards.get('TWM-130') === 3, 'set code and number pick the card');
ok(r.cards.get('SFA-38') === 1 && r.cards.get('PAL-172') === 3 && r.cards.get('SFA-61') === 4, 'the exact print when the game has it');
ok(r.cards.get('Psychic Energy') === 5 && r.cards.get('Fire Energy') === 5 && r.cards.get('Darkness Energy') === 5, 'Basic {P} Energy SVE 5 is Psychic Energy');
ok(r.cards.get('SVI-186') === 1, 'a name that ends in a number (Pokégear 3.0)');
ok(r.missing.map(m => m.name).join() === 'Battle VIP Pass FST 225', `a card the game doesn't have is reported (${r.missing.map(m => m.name)})`);
ok(r.total === 56 && !r.fixed.length && !r.swapped.length, `56 cards read, nothing guessed (${r.total})`);
ok(r.missing[0].n === 4, 'with its count');
ok(r.cards.get(printOf(ix, 'Rare Candy')) === 4, 'a print the game lacks (Rare Candy SVI 191) is read as the one decks play, silently, when it does the same');

// ---- the old Pokémon TCG Online format
r = parseDeckList(`****** Pokémon Trading Card Game Deck List ******

##Pokémon - 7

* 4 Dreepy TWM 128
* 3 Drakloak TWM 129

##Trainer Cards - 4

* 4 Ultra Ball SVI 196

##Energy - 6

* 6 Psychic Energy Energy 5

Total Cards - 17

****** Deck List Generated by the Pokémon TCG Online www.pokemon.com/TCGO ******`, ix);
ok(r.total === 17 && r.cards.get('Psychic Energy') === 6 && r.cards.get('SVI-196') === 4 && !r.missing.length, `Pokémon TCG Online lists (${JSON.stringify(list(r.cards))}, ${JSON.stringify(r.missing)})`);

// ---- typed by hand: counts before or after, capitals, accents, curly quotes, hyphens
r = parseDeckList(['4x dreepy', 'Drakloak x4', '3 DRAGAPULT EX', '2 boss’s orders', '1 chien pao ex', '2 Poke Pad', '10 Psychic Energy', '1 Basic Fire Energy', '2 {D} Energy'].join('\n'), ix);
ok(r.cards.get('TWM-128') === 4 && r.cards.get('TWM-129') === 4 && r.cards.get('TWM-130') === 3, '4x, x4 and capitals');
ok(r.cards.get(printOf(ix, "Boss's Orders")) === 2 && r.cards.get('PAL-61') === 1 && r.cards.get('POR-81') === 2, 'curly quotes, hyphens and accents');
ok(r.cards.get('Psychic Energy') === 10 && r.cards.get('Fire Energy') === 1 && r.cards.get('Darkness Energy') === 2, 'basic Energy however it is written');
ok(!r.missing.length && !r.fixed.length && r.total === 29, `all read exactly (${r.total}, ${JSON.stringify(r.missing)})`);
r = parseDeckList('4 Dreepy (TWM 128)\n2 Dreepy [TWM-128]\n1 Ultra Ball (SVI) 196\n1 Ultra Ball SVI 196 PH', ix);
ok(r.cards.get('TWM-128') === 4 && r.cards.get('SVI-196') === 2 && r.clamped.includes('Dreepy'), `prints in brackets, PH marks, and no more than 4 of a name (${JSON.stringify(list(r.cards))})`);

// ---- prints: different cards with one name, reprints, a print the game doesn't have
r = parseDeckList('1 Dunsparce PAL 156\n1 Dunsparce TEF 128\n1 Dunsparce JTG 120', ix);
ok(r.cards.get('PAL-156') === 1 && r.cards.get('TEF-128') === 1 && r.cards.get('JTG-120') === 1, 'three different Dunsparce kept apart by their numbers');
r = parseDeckList('2 Dunsparce PAF 74', ix);
ok(r.cards.size === 1 && r.swapped.length === 1 && r.swapped[0].to === printOf(ix, 'Dunsparce'), 'a print the game lacks, of a card with versions that differ, says so');
r = parseDeckList('2 Ultra Ball SVI 196\n2 Ultra Ball MEG 131\n2 Ultra Ball PAF 91', ix);
ok(r.cards.size === 1 && r.cards.get('SVI-196') === 4 && r.clamped.includes('Ultra Ball') && !r.swapped.length, `reprints of one card are one card (${JSON.stringify(list(r.cards))})`);
r = parseDeckList('4 Dreepy TWM 129', ix);
ok(r.cards.get('TWM-128') === 4, 'a wrong number with the right name: the name wins');
r = parseDeckList('4 Dreepxyz TWM 128', ix);
ok(r.cards.get('TWM-128') === 4 && r.fixed.length === 1, 'a garbled name with the right number: the number wins, and says so');

// ---- typos and cards the game doesn't have
r = parseDeckList('3 Dragapult ec\n4 Pikachoo ex\n2 Charizard VMAX\n1 Mewtwo V-UNION\n4 Ultra Bal', ix);
ok(r.fixed.some(f => f.from === 'Dragapult ec' && f.to === 'TWM-130') && r.fixed.some(f => f.from === 'Pikachoo ex' && db[f.to].name === 'Pikachu ex') && r.fixed.some(f => f.from === 'Ultra Bal'), `typos read as the closest card (${JSON.stringify(r.fixed)})`);
const charm = r.missing.find(m => m.name === 'Charizard VMAX');
ok(charm && charm.n === 2 && charm.suggestions.some(k => db[k].name === 'Charizard ex'), `a card the game doesn't have, with suggestions (${charm && charm.suggestions.map(k => db[k].name)})`);
ok(r.missing.some(m => m.name === 'Mewtwo V-UNION'), 'every card the game doesn’t have is listed');
r = parseDeckList('My Dragon Deck\n4 Dreepy', ix);
ok(r.name === 'My Dragon Deck' && r.total === 4 && !r.missing.length, 'a first line that isn’t a card is the deck’s name');

// ---- the rules check, in words
const rule = (cards, id) => deckRules(cards, db).find(x => x.id === id);
const base = sortDeck(drag.cards, db);
ok(deckRules(base, db).every(x => x.ok), 'a tournament deck keeps every rule');
const less = base.map(([k, n]) => (k === 'Psychic Energy' ? [k, n - 1] : [k, n]));
ok(!rule(less, 'size').ok && /Yours has 59: add 1 more/.test(rule(less, 'size').text), 'too few cards, in words');
const more = [...base, ['Psychic Energy', 3]];
ok(!rule(more, 'size').ok && /take 3 out/.test(rule(more, 'size').text), 'too many cards, in words');
const fiveBoss = [...base, ['PAL-172', 2]];
ok(!rule(fiveBoss, 'copies').ok && /Boss's Orders \(5\)/.test(rule(fiveBoss, 'copies').text), 'more than 4 of a name, across prints');
ok(rule([['Psychic Energy', 20]], 'copies').ok, 'basic Energy can be as many as you like');
ok(!rule(base.filter(([k]) => !(db[k].cat === 'P' && db[k].stage === 'Basic')), 'basic').ok, 'no Basic Pokémon');
ok(!rule([...base, ['TEF-157', 1]], 'ace').ok && /Unfair Stamp and Prime Catcher|Prime Catcher and Unfair Stamp/.test(rule([...base, ['TEF-157', 1]], 'ace').text), 'two ACE SPEC cards, named');
ok(!rule([['ASR-46', 1], ['CRZ-20', 1]], 'radiant').ok, 'two Radiant Pokémon');
ok(deckProblems(more, db).length === 1, 'only the broken rules are problems');
// what can't be added
ok(/up to 4 cards called Dreepy/.test(cantAdd(base, db, 'TWM-128')), 'a fifth Dreepy');
ok(cantAdd(base, db, 'Psychic Energy') === null, 'more basic Energy');
ok(/already have Unfair Stamp/.test(cantAdd(base, db, 'TEF-157')), 'a second ACE SPEC');
ok(/already have Radiant Greninja/.test(cantAdd([['ASR-46', 1]], db, 'CRZ-20')), 'a second Radiant Pokémon');
ok(/Only 1 Radiant/.test(cantAdd([['ASR-46', 1]], db, 'ASR-46')), 'a second copy of a Radiant Pokémon');
ok(cantAdd(base, db, 'TWM-95') === null, 'a third Munkidori is fine');
// tips that don't stop a deck playing
ok(deckTips(base, db).length === 0, 'no tips for a tournament deck');
ok(deckTips([['TWM-130', 4], ['Psychic Energy', 10]], db).some(t => /evolves from Drakloak/.test(t.text)), 'an evolution with nothing to evolve from');
ok(deckTips([['TWM-128', 4], ['Grass Energy', 10]], db).some(t => t.id === 'energy'), 'Pokémon that can’t attack with the deck’s Energy');
ok(energyMissing(db['TWM-128'], energyMade([['Grass Energy', 1]], db)).join() === 'Psychic' && !energyMissing(db['TWM-128'], energyMade([['Psychic Energy', 1]], db)).length, 'the Energy a Pokémon is missing');
ok(Math.abs(handChance(60, 10) - 0.738) < 0.01 && handChance(60, 0) === 0, `the chance of a Basic Pokémon in an opening hand (${handChance(60, 10).toFixed(3)})`);
// the order lists show cards in
const sorted = sortDeck(drag.cards.slice().reverse(), db);
ok(sorted.length === drag.cards.length && sorted[0][0] === 'TWM-128' && db[sorted[sorted.length - 1][0]].cat === 'E', 'Pokémon by evolution line first, Energy last');
ok(deckLook({ cards: drag.cards }, db).featured === 'TWM-130' && deckLook({ cards: drag.cards, featured: 'TWM-95' }, db).featured === 'TWM-95', 'the deck’s picture: the biggest Pokémon ex, or the one you chose');

// ---- the packed form rooms and replays carry
const mine = { id: 'pkc-test1234', name: 'My Dragon Deck', cards: base, featured: 'TWM-95', custom: true };
const packed = JSON.parse(JSON.stringify(packDeck(mine)));
const back = unpackDeck(packed, db);
ok(back && JSON.stringify(back.cards) === JSON.stringify(mine.cards) && back.name === mine.name && back.featured === 'TWM-95', 'a deck packs and unpacks to the same cards, in the same order');
ok(fingerprint(back.cards) === fingerprint(mine.cards) && fingerprint(mine.cards) !== fingerprint(mine.cards.slice().reverse()), 'the fingerprint follows the cards and their order');
ok(unpackDeck({ ...packed, l: packed.l + '|XYZ-999' }, db) === null, 'a deck with a card this browser doesn’t have is refused');
ok(unpackDeck({ ...packed, l: packed.l.replace('Psychic Energy*3', 'Psychic Energy*2') }, db) === null, 'a deck that breaks the rules is refused');
ok(unpackDeck({ ...packed, i: 'dragapult' }, db) === null, 'a deck must have a deck builder’s id');
const ref = deckRef(mine);
ok(/^pkc-test1234@[a-z0-9]+$/.test(ref) && deckRef(drag) === 'dragapult', `a seat names your deck with its fingerprint (${ref})`);
ok(findDeck(decks, ref) === null, 'not found before it arrives');
registerDeck(back);
ok(findDeck(decks, ref) && JSON.stringify(findDeck(decks, ref).cards) === JSON.stringify(mine.cards), 'found by its fingerprint once it arrives');
ok(findDeck(decks, 'pkc-test1234@zzzz') === null, 'another version of it is not this one');
ok(findDeck(decks, 'dragapult') === drag && findDeck(decks, 'pkc-test1234') === null, 'tournament decks by id (and nothing kept on a device in Node)');
const other = { ...mine, id: 'pkc-other567', cards: sortDeck(decks.find(d => d.id === 'charizard').cards, db) };
registerPacked(JSON.parse(JSON.stringify(packDeck(other))), db);
ok(findDeck(decks, deckRef(other)) && findDeck(decks, deckRef(other)).name === mine.name, 'a deck from someone’s room presence');
registerPacked({ ...packDeck(other), i: 'pkc-broken99', l: 'TWM-128*5' }, db);
ok(findDeck(decks, 'pkc-broken99@x') === null, 'and not one that breaks the rules');

// ---- save codes: two devices' Pokémon decks combined, a deleted one stays deleted
const devA = { 'pk-custom-decks': JSON.stringify([{ id: 'pkc-aaaa1111', name: 'A new', cards: base, updated: 5 }]), 'pa-custom-decks': JSON.stringify([{ id: 'custom-mtg1', name: 'Commander deck', commanders: [], cards: [], updated: 3 }]) };
const devB = { 'pk-custom-decks': JSON.stringify([{ id: 'pkc-bbbb2222', name: 'B', cards: base, updated: 6 }, { id: 'pkc-aaaa1111', name: 'A old', cards: base, updated: 2 }, { id: 'pkc-cccc3333', name: 'C', cards: base, updated: 9 }]), 'pk-deleted-decks': JSON.stringify(['pkc-cccc3333']) };
const merged = mergeSaves(devA, devB);
const ids = JSON.parse(merged['pk-custom-decks']).map(d => `${d.id}:${d.name}`);
ok(ids.join() === 'pkc-bbbb2222:B,pkc-aaaa1111:A new', `save codes combine Pokémon decks (${ids})`);
ok(JSON.parse(merged['pa-custom-decks']).length === 1 && JSON.parse(merged['pk-deleted-decks'])[0] === 'pkc-cccc3333', 'Commander decks as before, and the deleted one remembered');
ok(summarize(merged).decks === 3, 'and count them all');

console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);

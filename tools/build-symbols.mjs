// Builds src/ui/generated/symbols.css: subsetted Mana (mana symbols, card types) and Keyrune (set symbols)
// fonts inlined as data URIs, with only the CSS rules the app uses.
// Usage: node tools/build-symbols.mjs <mana-font package dir> <keyrune package dir> <pyftsubset path>
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { execFileSync } from 'node:child_process';

const [manaDir, keyruneDir, pyftsubset] = process.argv.slice(2);
if (!manaDir || !keyruneDir || !pyftsubset) { console.error('usage: node tools/build-symbols.mjs <mana-font dir> <keyrune dir> <pyftsubset>'); process.exit(1); }

const decks = JSON.parse(fs.readFileSync('data/decks.json', 'utf8'));

// split a stylesheet into { selectors, body } rules (no nesting in these files except @font-face)
function rules(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const out = [];
  const re = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(css))) out.push({ sel: m[1].trim(), body: m[2].trim() });
  return out;
}

function build({ dir, css, font, family, prefix, keep, baseSel }) {
  const all = rules(fs.readFileSync(path.join(dir, 'css', css), 'utf8')).filter(r => !r.sel.startsWith('@'));
  const classRe = new RegExp(`\\.${prefix}-([\\w-]+)`, 'g');
  const okSel = s => { const cls = [...s.matchAll(classRe)].map(m => m[1]); return cls.length > 0 && cls.every(c => keep.has(c)); };
  const kept = [];
  const cps = new Set();
  for (const r of all) {
    if (r.sel === baseSel) { kept.push(r); continue; }
    const sels = r.sel.split(',').map(s => s.trim()).filter(okSel);
    if (!sels.length) continue;
    kept.push({ sel: sels.join(', '), body: r.body });
    for (const m of r.body.matchAll(/content:\s*"\\([0-9a-f]+)"/gi)) cps.add(parseInt(m[1], 16));
  }
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sym-'));
  const outFont = path.join(tmp, 'out.woff2');
  execFileSync(pyftsubset, [path.join(dir, 'fonts', font), `--unicodes=${[...cps].map(c => 'U+' + c.toString(16)).join(',')}`, '--flavor=woff2', `--output-file=${outFont}`, '--no-hinting', '--layout-features=']);
  const b64 = fs.readFileSync(outFont).toString('base64');
  const face = `@font-face{font-family:"${family}";src:url(data:font/woff2;base64,${b64}) format("woff2");font-weight:normal;font-style:normal;font-display:block}`;
  const body = kept.map(r => `${r.sel}{${r.body.replace(/\s*\n\s*/g, '')}}`).join('\n');
  return { css: face + '\n' + body, glyphs: cps.size, bytes: b64.length };
}

const manaKeep = new Set(['cost', 'tap', 'untap', 'e', 'chaos', 's', 'x', 'y', 'z', 'c', 'w', 'u', 'b', 'r', 'g', 'p', 'shadow', 'creature', 'land', 'artifact', 'enchantment', 'planeswalker', 'instant', 'sorcery', 'battle', 'multiple', 'loyalty-up', 'loyalty-down', 'loyalty-zero', 'loyalty-start', 'loyalty-0', 'loyalty-1', 'loyalty-2', 'loyalty-3', 'loyalty-4', 'loyalty-5', 'loyalty-6', 'loyalty-7', 'loyalty-8', 'loyalty-9', 'loyalty-10', 'half', 'fw', 'ds', 'tribal', 'infinity']);
for (let i = 0; i <= 20; i++) manaKeep.add(String(i));
for (const a of 'wubrg') { manaKeep.add(a + 'p'); manaKeep.add('2' + a); manaKeep.add('c' + a); for (const b of 'wubrg') if (a !== b) { manaKeep.add(a + b); manaKeep.add(a + b + 'p'); } }
const mana = build({ dir: manaDir, css: 'mana.css', font: 'mana.woff2', family: 'Mana', prefix: 'ms', keep: manaKeep, baseSel: '.ms' });

const sets = new Set(decks.map(d => d.set.toLowerCase()));
const keyruneKeep = new Set([...sets, 'common', 'uncommon', 'rare', 'mythic', 'grad', 'fw', 'pmtg1', 'cmd']);
const key = build({ dir: keyruneDir, css: 'keyrune.css', font: 'keyrune.woff2', family: 'Keyrune', prefix: 'ss', keep: keyruneKeep, baseSel: '.ss' });

const header = '/* Generated by tools/build-symbols.mjs from mana-font (MIT, Andrew Gioia) and keyrune (font OFL-1.1, Andrew Gioia). Do not edit. */\n';
const css = header + mana.css.replace(/font:\s*normal normal normal 14px Mana;?/, 'font:normal normal normal 14px Mana;') + '\n' + key.css;
fs.writeFileSync('src/ui/generated/symbols.css', css);
const missing = [...sets].filter(s => !new RegExp(`\\.ss-${s}[:\\s,{]`).test(key.css));
console.log(`symbols.css ${(css.length / 1024).toFixed(0)}KB · mana ${mana.glyphs} glyphs ${(mana.bytes / 1024).toFixed(0)}KB · keyrune ${key.glyphs} glyphs ${(key.bytes / 1024).toFixed(0)}KB · sets without a symbol: ${missing.join(' ') || 'none'}`);
